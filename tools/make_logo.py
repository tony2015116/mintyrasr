#!/usr/bin/env python3
"""Build man/figures/logo.svg (+ favicons) in the style of the mintyr logo.

Wordmark: Audiowide (OFL), converted to outlines so the logo needs no font.
Get the font with:  npm pack @fontsource/audiowide && tar xzf fontsource-audiowide-*.tgz
Run from the package root:  python3 tools/make_logo.py <path to audiowide-latin-400-normal.woff>
Favicons need rsvg-convert and ImageMagick (convert).
"""
import pathlib, subprocess, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = pathlib.Path(__file__).resolve().parents[1]
GREEN, LIGHT, MID = "#2A6E3F", "#DDF3DF", "#9BD8A4"
W, H, CX, CY = 124.44, 144.00, 62.15, 72.07
DEJAVU = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


def text_paths(fontfile, text, size, cx=None, baseline=0.0, x0=None, fill=GREEN):
    """Outlined text; centred on cx (or starting at x0) with the given baseline."""
    f = TTFont(fontfile); gs = f.getGlyphSet(); cmap = f.getBestCmap()
    s = size / f["head"].unitsPerEm
    adv, glyphs = 0, []
    for ch in text:
        g = cmap[ord(ch)]; glyphs.append((g, adv)); adv += gs[g].width
    width = adv * s
    left = x0 if x0 is not None else cx - width / 2
    out = []
    for g, a in glyphs:
        pen = SVGPathPen(gs); gs[g].draw(pen)
        if pen.getCommands():
            out.append(f'<path transform="translate({left + a * s:.3f},{baseline:.3f}) '
                       f'scale({s:.5f},{-s:.5f})" d="{pen.getCommands()}"/>')
    return f'<g fill="{fill}">' + "".join(out) + "</g>", width


def hexagon(r):
    import math
    pts = [(CX + r * math.cos(math.radians(a)), CY + r * math.sin(math.radians(a)))
           for a in (-90, -30, 30, 90, 150, 210)]
    return " ".join(f"{x:.2f},{y:.2f}" for x, y in pts)


def leaf(x, y, rot, scale=1.0):
    """A mint leaf with a mid-rib and veins, like the one on the mintyr tea bag."""
    return f'''<g transform="translate({x},{y}) rotate({rot}) scale({scale})">
  <path d="M0,0 C4,-6 12,-7 17,0 C12,7 4,6 0,0 Z" fill="#3FAE5A" stroke="#1E1E1E" stroke-width="0.9" stroke-linejoin="round"/>
  <path d="M0.5,0 L15.5,0 M5,0 L8,-3.2 M5,0 L8,3.2 M9.5,0 L12,-2.6 M9.5,0 L12,2.6"
        fill="none" stroke="#1E1E1E" stroke-width="0.7" stroke-linecap="round"/>
</g>'''


def build(audiowide):
    title, tw = text_paths(audiowide, "mintyrasr", 17.2, cx=CX, baseline=47.5)
    # URL along the lower-right edge (from (62.15, 142.59) to (123.22, 107.33)),
    # centred on its midpoint, moved 5.8 units inwards
    url, _ = text_paths(DEJAVU, "https://tony2015116.github.io/mintyrasr/", 3.55, cx=0, baseline=0,
                        fill="#000000")
    ink = 'stroke="#1E1E1E" stroke-width="1.25" stroke-linejoin="round" stroke-linecap="round"'
    art = f'''
<!-- saucer -->
<ellipse cx="60" cy="113.2" rx="27" ry="4.2" fill="#FFFFFF" {ink}/>
<!-- handle -->
<path d="M80.5,84.5 C92,82.5 94.5,95 82.5,101.5" fill="none" stroke="#1E1E1E" stroke-width="5.2" stroke-linecap="round"/>
<path d="M80.5,84.5 C92,82.5 94.5,95 82.5,101.5" fill="none" stroke="#FFFFFF" stroke-width="2.6" stroke-linecap="round"/>
<!-- cup -->
<path d="M37.5,77 L82.5,77 C82.5,95 78,108.5 69,111 L51,111 C42,108.5 37.5,95 37.5,77 Z" fill="#FFFFFF" {ink}/>
<path d="M39.2,86 L80.8,86 C80,98 76.5,107.3 68.6,109.4 L51.4,109.4 C43.5,107.3 40,98 39.2,86 Z" fill="{LIGHT}" stroke="none"/>
<path d="M40.6,95 L79.4,95 C77.6,103 74.5,107.7 68.6,109.4 L51.4,109.4 C45.5,107.7 42.4,103 40.6,95 Z" fill="{MID}" stroke="none" opacity="0.75"/>
<path d="M37.5,77 L82.5,77 C82.5,95 78,108.5 69,111 L51,111 C42,108.5 37.5,95 37.5,77 Z" fill="none" {ink}/>
<!-- tea surface -->
<ellipse cx="60" cy="77" rx="22.5" ry="3.6" fill="{MID}" {ink}/>
{leaf(50, 77.2, -18, 0.62)}
{leaf(58, 77.6, 12, 0.55)}
<!-- tea bag string over the rim and its tag -->
<path d="M64,76.2 C66,66 74,62 80,63.5 C85.5,65 87,70.5 86.4,75.5" fill="none" stroke="#1E1E1E" stroke-width="0.9"/>
<rect x="82.9" y="75.3" width="7" height="8.2" rx="0.8" fill="#3FAE5A" stroke="#1E1E1E" stroke-width="1"/>
<!-- steam -->
<path d="M51,70 C48.5,66 53.5,63.5 51,59.5" fill="none" stroke="{GREEN}" stroke-width="1.5" stroke-linecap="round"/>
<path d="M58.5,68.5 C56,64.5 61,62 58.5,58" fill="none" stroke="{GREEN}" stroke-width="1.5" stroke-linecap="round"/>
'''
    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- mintyrasr logo, sibling of the mintyr logo. Generated by tools/make_logo.py.
     Wordmark: Audiowide (SIL Open Font License), outlined. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}">
<polygon points="{hexagon(71.2)}" fill="{GREEN}"/>
<polygon points="{hexagon(68.0)}" fill="#FFFFFF"/>
{title}
{art}
<g transform="translate(89.80,119.95) rotate(-30)">{url}</g>
</svg>
'''
    out = ROOT / "man" / "figures" / "logo.svg"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(svg, encoding="utf-8")
    print("written:", out, f"(title width {tw:.1f})")

    fav = ROOT / "pkgdown" / "favicon"
    fav.mkdir(parents=True, exist_ok=True)
    sizes = {"apple-touch-icon.png": 180, "apple-touch-icon-180x180.png": 180,
             "apple-touch-icon-152x152.png": 152, "apple-touch-icon-120x120.png": 120,
             "apple-touch-icon-76x76.png": 76, "apple-touch-icon-60x60.png": 60,
             "favicon-32x32.png": 32, "favicon-16x16.png": 16}
    for name, px in sizes.items():
        subprocess.run(["rsvg-convert", "-h", str(px), str(out), "-o", str(fav / name)], check=True)
    subprocess.run(["convert", str(fav / "favicon-16x16.png"), str(fav / "favicon-32x32.png"),
                    str(fav / "favicon.ico")], check=True)
    print("written:", fav)


if __name__ == "__main__":
    build(sys.argv[1])
